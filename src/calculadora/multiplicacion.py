def multiplicacion(a, b):
    """Multiplica dos números y retorna el resultado.
    
    Args:
        a: Primer número (int o float)
        b: Segundo número (int o float)
        
    Returns:
        El producto de a y b
    """
    return a * b


if __name__ == "__main__":
    print(multiplicacion(5, 3))  # 15
    print(multiplicacion(-2, 4))  # -8

